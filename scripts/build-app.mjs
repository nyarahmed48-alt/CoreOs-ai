/**
 * Finishes the installable build: names the entry page index.html, and writes
 * a service worker that lists exactly what this build produced.
 *
 * The worker is generated rather than hand-written because the asset names
 * carry content hashes — a precache list typed by hand goes stale on the next
 * build, and a till that caches a file that no longer exists is a till that
 * opens to a blank screen.
 */

import { readdirSync, readFileSync, renameSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const OUT = "dist-app";
const build = new Date().toISOString().slice(0, 16).replace("T", " ");

// Vite names the output after its input; the page a shop opens should be the
// plain index of the folder.
renameSync(join(OUT, "app-index.html"), join(OUT, "index.html"));

function walk(dir) {
  const found = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) found.push(...walk(full));
    else found.push("./" + relative(OUT, full).split("\\").join("/"));
  }
  return found;
}

const files = walk(OUT).filter((file) => file !== "./sw.js");

const sw = `/**
 * CoreCashier — offline worker. Generated by scripts/build-app.mjs.
 * Build ${build}
 */

const CACHE = "corecashier-${build.replace(/[^0-9]/g, "")}";
const FILES = ${JSON.stringify(files, null, 2)};

/* Vary must be ignored, and this is not a detail.
 *
 * Static hosts answer with "Vary: Origin" or "Vary: Accept-Encoding" — the one
 * this was found on sends Origin. The Cache API honours Vary when it matches,
 * so a module script, which is fetched as CORS and carries an Origin header,
 * failed to match the very file the worker had just precached. The till opened
 * to a blank screen the first time the internet went away: the shell was
 * served, nothing else was, and the shop would have had no idea why. */
const MATCH = { ignoreVary: true };

/* Everything this build needs, fetched once while the shop still has a
   connection. After this the till never needs one again. */
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(FILES)),
  );
});

/* Old builds are cleared only once the new one takes over, so a till that is
   mid-sale when an update arrives keeps the files it is running on. */
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names.filter((name) => name !== CACHE).map((name) => caches.delete(name)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;

  // Never touch anything that is not a plain read of our own files: posting a
  // sale to a server, a WhatsApp link, a camera stream.
  if (request.method !== "GET") return;
  if (new URL(request.url).origin !== self.location.origin) return;

  // A navigation always gets the app shell. This is what makes the till open
  // instantly on a cold tablet with no signal.
  if (request.mode === "navigate") {
    event.respondWith(
      caches.match("./index.html", MATCH).then((hit) => hit ?? fetch(request)),
    );
    return;
  }

  event.respondWith(
    caches.match(request, MATCH).then((hit) => {
      if (hit) return hit;
      return fetch(request)
        .then((response) => {
          // Keep anything new this build asks for — the barcode decoder is
          // loaded on demand, and a shop should not need a connection the
          // first time someone opens the camera.
          if (response.ok && response.type === "basic") {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => hit);
    }),
  );
});
`;

writeFileSync(join(OUT, "sw.js"), sw);

const total = files.reduce(
  (sum, file) => sum + statSync(join(OUT, file.slice(2))).size,
  0,
);
console.log(
  `${OUT}/ — ${files.length} files, ${(total / 1024).toFixed(0)} kB, precached by sw.js (build ${build})`,
);
